// Code generation driver for both brainpoolP256r1 fields.
//
//	go run generate.go -field p   # p_fiat64.go, p_invert.go  (mod the field prime)
//	go run generate.go -field n   # n_fiat64.go, n_invert.go  (mod the group order)
//
// The *_fiat64.go arithmetic is emitted by Fiat Cryptography (machine-checked
// Coq → Go) inside the pinned fiat-crypto:v0.0.9 image, the same image and
// flags the Go standard library uses for its nistec field elements; build the
// image once from PROVENANCE.md. The *_invert.go inversion is an addition chain
// for x^(m−2) emitted by mmcloughlin/addchain. The hand-written wrappers
// element.go and scalar.go are not generated.

//go:build ignore

package main

import (
	"bytes"
	"flag"
	"go/format"
	"log"
	"os"
	"os/exec"
	"strings"
)

// Both moduli come from RFC 5639 §3.4. Neither has a special reduction
// structure, so word-by-word Montgomery is the right synthesizer for both.
// fiat-crypto takes the hex form, addchain the decimal form.
var fields = map[string]struct {
	prefix   string // symbol prefix inside the generated code
	typeName string // wrapper type the inversion chain is generated for
	symbol   string // p or n, for the doc comment
	hex, dec string
}{
	"p": {"bp256", "Element", "p",
		"0xA9FB57DBA1EEA9BC3E660A909D838D726E3BF623D52620282013481D1F6E5377",
		"76884956397045344220809746629001649093037950200943055203735601445031516197751"},
	"n": {"bp256n", "Scalar", "n",
		"0xA9FB57DBA1EEA9BC3E660A909D838D718C397AA3B561A6F7901E0E82974856A7",
		"76884956397045344220809746629001649092737531784414529538755519063063536359079"},
}

func main() {
	which := flag.String("field", "", "p or n")
	flag.Parse()
	f, ok := fields[*which]
	if !ok {
		log.Fatal("-field must be p or n")
	}

	log.Printf("Generating %s_fiat64.go (fiat-crypto:v0.0.9)...", *which)
	cmd := exec.Command("docker", "run", "--rm", "--platform", "linux/amd64",
		"--entrypoint", "word_by_word_montgomery", "fiat-crypto:v0.0.9",
		"--lang", "Go", "--no-wide-int", "--cmovznz-by-mul",
		"--relax-primitive-carry-to-bitwidth", "32,64", "--internal-static",
		"--public-function-case", "camelCase", "--public-type-case", "camelCase",
		"--private-function-case", "camelCase", "--private-type-case", "camelCase",
		"--doc-text-before-function-name", "", "--doc-newline-before-package-declaration",
		"--doc-prepend-header", "Code generated by Fiat Cryptography. DO NOT EDIT.",
		"--package-name", "fiat", "--no-prefix-fiat", f.prefix, "64", f.hex,
		"mul", "square", "add", "sub", "one", "from_montgomery", "to_montgomery",
		"selectznz", "to_bytes", "from_bytes")
	cmd.Stderr = os.Stderr
	out, err := cmd.Output()
	if err != nil {
		log.Fatal(err)
	}
	if out, err = format.Source(out); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*which+"_fiat64.go", out, 0644); err != nil {
		log.Fatal(err)
	}

	log.Printf("Generating %s_invert.go (addchain)...", *which)
	search := exec.Command("addchain", "search", f.dec+" - 2")
	search.Stderr = os.Stderr
	chain, err := search.Output()
	if err != nil {
		log.Fatal(err)
	}
	chainFile, err := os.CreateTemp("", "bp256-addchain")
	if err != nil {
		log.Fatal(err)
	}
	defer os.Remove(chainFile.Name())
	if _, err := chainFile.Write(chain); err != nil {
		log.Fatal(err)
	}
	if err := chainFile.Close(); err != nil {
		log.Fatal(err)
	}
	tmpl := strings.NewReplacer("TYPE", f.typeName, "MOD", f.symbol).Replace(invertTmpl)
	tmplFile, err := os.CreateTemp("", "bp256-invert-tmpl")
	if err != nil {
		log.Fatal(err)
	}
	defer os.Remove(tmplFile.Name())
	if err := os.WriteFile(tmplFile.Name(), []byte(tmpl), 0644); err != nil {
		log.Fatal(err)
	}
	gen := exec.Command("addchain", "gen", "-tmpl", tmplFile.Name(), chainFile.Name())
	gen.Stderr = os.Stderr
	out, err = gen.Output()
	if err != nil {
		log.Fatal(err)
	}
	if out, err = format.Source(bytes.TrimSpace(out)); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*which+"_invert.go", out, 0644); err != nil {
		log.Fatal(err)
	}
	log.Println("Done.")
}

const invertTmpl = `// Code generated by {{ .Meta.Name }}. DO NOT EDIT.

package fiat

// Invert sets e = 1/x mod MOD, and returns e.
//
// If x == 0, Invert returns e = 0.
func (e *TYPE) Invert(x *TYPE) *TYPE {
	// Inversion is implemented as exponentiation with exponent MOD − 2.
	// The sequence of {{ .Ops.Adds }} multiplications and {{ .Ops.Doubles }} squarings is derived from the
	// following addition chain generated with {{ .Meta.Module }} {{ .Meta.ReleaseTag }}.
	//
	{{- range lines (format .Script) }}
	//	{{ . }}
	{{- end }}
	//

	var z = new(TYPE).Set(e)
	{{- range .Program.Temporaries }}
	var {{ . }} = new(TYPE)
	{{- end }}
	{{ range $i := .Program.Instructions -}}
	{{- with add $i.Op }}
	{{ $i.Output }}.Mul({{ .X }}, {{ .Y }})
	{{- end -}}

	{{- with double $i.Op }}
	{{ $i.Output }}.Square({{ .X }})
	{{- end -}}

	{{- with shift $i.Op -}}
	{{- $first := 0 -}}
	{{- if ne $i.Output.Identifier .X.Identifier }}
	{{ $i.Output }}.Square({{ .X }})
	{{- $first = 1 -}}
	{{- end }}
	for s := {{ $first }}; s < {{ .S }}; s++ {
		{{ $i.Output }}.Square({{ $i.Output }})
	}
	{{- end -}}
	{{- end }}

	return e.Set(z)
}
`
