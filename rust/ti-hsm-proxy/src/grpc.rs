//! The gRPC transport: `gematik.zetaguard.hsmproxy.v1.HsmProxyService` as `hsm-proxy.proto`
//! defines it (gemSpec_ZETA A_28829) and `grpc.health.v1`, on a Unix domain socket.
//!
//! This module only decodes, calls [`HsmProxy`] on tokio's blocking pool, and encodes; it
//! decides nothing. Enum values the proto does not define, and `UNSPECIFIED` where an
//! algorithm is asked for, are refused, as ngx_pep's `hsm_sim` refuses them.

use std::future::Future;
use std::io;
use std::path::Path;
use std::sync::Arc;
use std::time::Duration;

use tokio::net::UnixListener;
use tokio_stream::wrappers::UnixListenerStream;
use tonic::{Request, Response, Status};

use crate::pkcs11::Sealed;
use crate::service::{Digest, Failure, FailureKind, HsmProxy, MAX_DATA_LEN};

/// The messages and the server generated from `proto/` by `just hsm-proxy-codegen`.
#[allow(
    missing_docs,
    clippy::all,
    clippy::pedantic,
    reason = "generated by tonic-prost-build; regenerated, never edited"
)]
pub mod proto {
    include!("generated/gematik.zetaguard.hsmproxy.v1.rs");
}

use proto::health_check_response::ServingStatus;
use proto::hsm_proxy_service_server::{HsmProxyService, HsmProxyServiceServer};
use proto::{
    DecryptRequest, DecryptResponse, DigestAlgorithm, EncryptRequest, EncryptResponse,
    GetCertificateRequest, GetCertificateResponse, GetPublicKeyRequest, GetPublicKeyResponse,
    HealthCheckRequest, HealthCheckResponse, SignRequest, SignResponse,
    SymmetricEncryptionAlgorithm,
};

/// The largest request the server decodes: the largest input, its associated data and
/// room for the other fields.
const MAX_MESSAGE_LEN: usize = 2 * MAX_DATA_LEN + 1024;

fn status(failure: Failure) -> Status {
    let code = match failure.kind {
        FailureKind::InvalidArgument => tonic::Code::InvalidArgument,
        FailureKind::NotFound => tonic::Code::NotFound,
        FailureKind::FailedPrecondition => tonic::Code::FailedPrecondition,
        FailureKind::Unimplemented => tonic::Code::Unimplemented,
        FailureKind::Unavailable => tonic::Code::Unavailable,
        _ => tonic::Code::Internal,
    };
    Status::new(code, failure.message)
}

fn aes_256_gcm(algorithm: i32) -> Result<(), Status> {
    match SymmetricEncryptionAlgorithm::try_from(algorithm) {
        Ok(SymmetricEncryptionAlgorithm::Aes256Gcm) => Ok(()),
        _ => Err(Status::invalid_argument("algorithm is AES_256_GCM")),
    }
}

struct Service {
    proxy: Arc<HsmProxy>,
}

impl Service {
    async fn run<T: Send + 'static>(
        &self,
        operation: impl FnOnce(&HsmProxy) -> Result<T, Failure> + Send + 'static,
    ) -> Result<T, Status> {
        let proxy = Arc::clone(&self.proxy);
        tokio::task::spawn_blocking(move || operation(&proxy))
            .await
            .map_err(|_| Status::internal("the operation did not finish"))?
            .map_err(status)
    }
}

#[tonic::async_trait]
impl HsmProxyService for Service {
    async fn sign(&self, request: Request<SignRequest>) -> Result<Response<SignResponse>, Status> {
        let SignRequest {
            key_id,
            data,
            algorithm,
        } = request.into_inner();
        let digest = match DigestAlgorithm::try_from(algorithm) {
            Ok(DigestAlgorithm::None) => Digest::None,
            Ok(DigestAlgorithm::Sha256) => Digest::Sha256,
            Ok(DigestAlgorithm::Sha384) => Digest::Sha384,
            Ok(DigestAlgorithm::Sha512) => Digest::Sha512,
            Err(_) => {
                return Err(Status::invalid_argument(
                    "algorithm is not a DigestAlgorithm",
                ));
            }
        };
        let (signature, key_id) = self
            .run(move |proxy| Ok((proxy.sign(&key_id, &data, digest)?, key_id)))
            .await?;
        Ok(Response::new(SignResponse { signature, key_id }))
    }

    async fn get_public_key(
        &self,
        request: Request<GetPublicKeyRequest>,
    ) -> Result<Response<GetPublicKeyResponse>, Status> {
        let key_id = request.into_inner().key_id;
        let key = self.run(move |proxy| proxy.public_key(&key_id)).await?;
        Ok(Response::new(GetPublicKeyResponse {
            public_key_pem: key.pem,
            public_key_der: key.der,
            jwk_json: key.jwk_json,
        }))
    }

    async fn encrypt(
        &self,
        request: Request<EncryptRequest>,
    ) -> Result<Response<EncryptResponse>, Status> {
        let EncryptRequest {
            key_id,
            plaintext,
            algorithm,
            associated_data,
        } = request.into_inner();
        aes_256_gcm(algorithm)?;
        let sealed = self
            .run(move |proxy| proxy.encrypt(&key_id, &plaintext, &associated_data))
            .await?;
        Ok(Response::new(EncryptResponse {
            ciphertext: sealed.ciphertext,
            iv: sealed.iv,
            tag: sealed.tag,
        }))
    }

    async fn decrypt(
        &self,
        request: Request<DecryptRequest>,
    ) -> Result<Response<DecryptResponse>, Status> {
        let DecryptRequest {
            key_id,
            ciphertext,
            algorithm,
            iv,
            tag,
            associated_data,
        } = request.into_inner();
        aes_256_gcm(algorithm)?;
        let sealed = Sealed {
            iv,
            ciphertext,
            tag,
        };
        let plaintext = self
            .run(move |proxy| proxy.decrypt(&key_id, &sealed, &associated_data))
            .await?;
        Ok(Response::new(DecryptResponse { plaintext }))
    }

    async fn get_certificate(
        &self,
        request: Request<GetCertificateRequest>,
    ) -> Result<Response<GetCertificateResponse>, Status> {
        let key_id = request.into_inner().key_id;
        let certificate = self.run(move |proxy| proxy.certificate(&key_id)).await?;
        Ok(Response::new(GetCertificateResponse {
            certificate_pem: certificate.pem,
            certificate_chain_pem: certificate.chain_pem,
        }))
    }

    async fn health_check(
        &self,
        _: Request<HealthCheckRequest>,
    ) -> Result<Response<HealthCheckResponse>, Status> {
        let health = self.run(|proxy| Ok(proxy.health())).await?;
        let status = if health.serving {
            ServingStatus::Serving
        } else {
            ServingStatus::NotServing
        };
        Ok(Response::new(HealthCheckResponse {
            status: status.into(),
            version: health.version.to_owned(),
            hsm_info: health.hsm_info,
        }))
    }
}

/// The name `grpc.health.v1` reports `HsmProxyService` under.
pub const SERVICE_NAME: &str = "gematik.zetaguard.hsmproxy.v1.HsmProxyService";

/// Serves `proxy` on the Unix socket at `socket` until `shutdown` completes. The socket is
/// for owner and group (mode 0660); a socket file left at the path is replaced only when
/// nothing answers on it, and any other file there is not.
///
/// `grpc.health.v1` follows the token: every `health_interval` a session is asked whether
/// the token answers ([`HsmProxy::health`]), and the overall status (`""`) and that of
/// [`SERVICE_NAME`] become `SERVING` or `NOT_SERVING`. The first check is made before the
/// socket is bound, so a probe never sees a status nobody checked.
///
/// # Errors
///
/// If the socket cannot be bound or the server fails.
pub async fn serve(
    proxy: Arc<HsmProxy>,
    socket: &Path,
    health_interval: Duration,
    shutdown: impl Future<Output = ()> + Send,
) -> io::Result<()> {
    remove_stale_socket(socket).await?;
    let listener = open_socket(socket)?;
    let (reporter, health) = tonic_health::server::health_reporter();
    report(&reporter, check(&proxy).await).await;
    let watcher = {
        let proxy = Arc::clone(&proxy);
        tokio::spawn(async move {
            let mut ticks = tokio::time::interval(health_interval);
            ticks.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Delay);
            ticks.tick().await;
            loop {
                ticks.tick().await;
                report(&reporter, check(&proxy).await).await;
            }
        })
    };
    let service =
        HsmProxyServiceServer::new(Service { proxy }).max_decoding_message_size(MAX_MESSAGE_LEN);
    let served = tonic::transport::Server::builder()
        .add_service(health)
        .add_service(service)
        .serve_with_incoming_shutdown(UnixListenerStream::new(listener), shutdown)
        .await
        .map_err(io::Error::other);
    watcher.abort();
    served
}

async fn check(proxy: &Arc<HsmProxy>) -> bool {
    let proxy = Arc::clone(proxy);
    tokio::task::spawn_blocking(move || proxy.health().serving)
        .await
        .unwrap_or(false)
}

async fn report(reporter: &tonic_health::server::HealthReporter, serving: bool) {
    let status = if serving {
        tonic_health::ServingStatus::Serving
    } else {
        tonic_health::ServingStatus::NotServing
    };
    reporter.set_service_status("", status).await;
    reporter.set_service_status(SERVICE_NAME, status).await;
}

/// Asks the sidecar on `socket` for its overall `grpc.health.v1` status: what
/// `hsm-proxy health` runs for an exec probe, since a kubelet's gRPC and HTTP probes do not
/// reach a Unix socket. `true` for `SERVING`.
///
/// # Errors
///
/// If the socket does not answer or the call fails.
pub async fn probe(socket: &Path) -> io::Result<bool> {
    use tonic_health::pb::health_check_response::ServingStatus as Status;
    use tonic_health::pb::health_client::HealthClient;

    let channel = connect(socket).await?;
    let response = HealthClient::new(channel)
        .check(tonic_health::pb::HealthCheckRequest {
            service: String::new(),
        })
        .await
        .map_err(|status| io::Error::other(status.message().to_owned()))?;
    Ok(response.into_inner().status == i32::from(Status::Serving))
}

/// A channel to the sidecar on `socket`.
///
/// # Errors
///
/// If the socket does not accept the connection.
pub async fn connect(socket: &Path) -> io::Result<tonic::transport::Channel> {
    let socket = socket.to_path_buf();
    tonic::transport::Endpoint::from_static("http://hsm-proxy")
        .connect_with_connector(tower::service_fn(move |_: tonic::transport::Uri| {
            let socket = socket.clone();
            async move {
                Ok::<_, io::Error>(hyper_util::rt::TokioIo::new(
                    tokio::net::UnixStream::connect(socket).await?,
                ))
            }
        }))
        .await
        .map_err(|e| {
            // tonic's transport error says only "transport error"; the cause is its source.
            let cause =
                std::error::Error::source(&e).map_or_else(String::new, |c| format!(": {c}"));
            io::Error::other(format!("{e}{cause}"))
        })
}

/// Removes a socket file an earlier run left at `socket`, but only when nothing answers on
/// it (rule 29): a second sidecar on the same path is refused, not displaced. Any other file
/// at the path is left alone.
async fn remove_stale_socket(socket: &Path) -> io::Result<()> {
    use std::os::unix::fs::FileTypeExt as _;
    match std::fs::symlink_metadata(socket) {
        Ok(meta) if meta.file_type().is_socket() => {
            match tokio::net::UnixStream::connect(socket).await {
                Ok(_) => Err(io::Error::new(
                    io::ErrorKind::AddrInUse,
                    format!("{}: another process answers on it", socket.display()),
                )),
                // Refused means bound by nobody: the file of a process that ended. Any other
                // failure, as no permission to connect, says nothing of that.
                Err(e) if e.kind() == io::ErrorKind::ConnectionRefused => {
                    std::fs::remove_file(socket)
                }
                Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(()),
                Err(e) => Err(io::Error::new(
                    e.kind(),
                    format!("{}: not known to be stale: {e}", socket.display()),
                )),
            }
        }
        Ok(_) => Err(io::Error::new(
            io::ErrorKind::AlreadyExists,
            format!("{} exists and is not a socket", socket.display()),
        )),
        Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(()),
        Err(e) => Err(e),
    }
}

/// Owner and group read and write, nothing for others: what lets the workload's container,
/// under another arbitrary UID with group 0 or the pod's `fsGroup`, connect (rules 27 and
/// 29). The socket gets the group of a directory with the setgid bit, as an `emptyDir` with
/// `fsGroup` has, or else the process's primary group, which is 0 on OpenShift.
const SOCKET_MODE: u32 = 0o660;

/// Binds the socket where nobody else can reach it, a directory of mode 0700 beside its
/// path, gives it [`SOCKET_MODE`] and only then links it to its path. However the umask is
/// set, the socket is never reachable with other permissions; and a link, unlike a rename,
/// does not replace a socket another process bound at the path meanwhile.
fn open_socket(socket: &Path) -> io::Result<UnixListener> {
    use std::os::unix::fs::{DirBuilderExt as _, PermissionsExt as _};
    let named = |e: io::Error| io::Error::new(e.kind(), format!("{}: {e}", socket.display()));
    let parent = socket
        .parent()
        .ok_or_else(|| named(io::Error::from(io::ErrorKind::InvalidInput)))?;
    let staging = parent.join(format!(".hsm-proxy-{}", std::process::id()));
    std::fs::DirBuilder::new()
        .mode(0o700)
        .create(&staging)
        .map_err(named)?;
    let inner = staging.join("s");
    let bound = UnixListener::bind(&inner).and_then(|listener| {
        std::fs::set_permissions(&inner, std::fs::Permissions::from_mode(SOCKET_MODE))?;
        std::fs::hard_link(&inner, socket)?;
        Ok(listener)
    });
    let _ = std::fs::remove_file(&inner);
    let _ = std::fs::remove_dir(&staging);
    bound.map_err(named)
}
