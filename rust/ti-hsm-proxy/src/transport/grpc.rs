//! The gRPC transport: `gematik.zetaguard.hsmproxy.v1.HsmProxyService` as `hsm-proxy.proto`
//! defines it (gemSpec_ZETA A_28829) and `grpc.health.v1`, on the listeners of
//! [`super::Listener`]. Over mTLS, an interceptor holds every call of the interface to the
//! listener's allowlist; `grpc.health.v1` answers without a client certificate (rule 31).
//!
//! This module only decodes, calls [`HsmProxy`] on tokio's blocking pool, and encodes; it
//! decides nothing. Enum values the proto does not define, and `UNSPECIFIED` where an
//! algorithm is asked for, are refused, as ngx_pep's `hsm_sim` refuses them.

