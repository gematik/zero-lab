//! The TCP listener inside the cluster against the sidecar on a software token (servers.md
//! rule 29): the sidecar's own mTLS with an allowlist, and plaintext for a declared mesh,
//! each with its health socket for `hsm-proxy health`.
//!
//! Gated like the token suite (`just hsm-proxy-softhsm2`). The CA and the certificates are
//! made by the test, keys included.

#![cfg(feature = "grpc")]

mod support;

use std::net::SocketAddr;
use std::num::NonZeroUsize;
use std::path::PathBuf;
use std::sync::{Arc, OnceLock};
use std::time::{Duration, SystemTime};

use cryptoki::types::AuthPin;
use support::pki::{Ca, Issued, dns, expired, loopback, uri, valid_for};
use ti_hsm_proxy::transport::tls::{Clients, TlsListener};
use ti_hsm_proxy::transport::{Listener, grpc};
use ti_hsm_proxy::{HsmProxy, Iv, KeyKind, KeySpec, MissingKeys, Module};
use tonic::Code;
use tonic::transport::{Certificate, Channel, ClientTlsConfig, Endpoint, Identity};

/// The messages and a client of the interface, generated beside the server.
#[allow(
    missing_docs,
    clippy::all,
    clippy::pedantic,
    reason = "generated by tonic-prost-build; regenerated, never edited"
)]
mod proto {
    include!("generated/gematik.zetaguard.hsmproxy.v1.rs");
}

use proto::SignRequest;
use proto::hsm_proxy_service_client::HsmProxyServiceClient;

const TOKEN: &str = "ti-hsm-proxy-tcp";

fn module() -> &'static Module {
    static MODULE: OnceLock<Module> = OnceLock::new();
    MODULE.get_or_init(|| {
        let path = std::env::var_os("TI_HSM_PKCS11_MODULE_PATH")
            .map(PathBuf::from)
            .expect(
                "TI_HSM_PKCS11_MODULE_PATH: the PKCS#11 module to drive (just hsm-proxy-softhsm2)",
            );
        let module = Module::load(&path).expect("the module loads");
        module
            .provision(
                TOKEN,
                &AuthPin::from("so-pin-TEST-ONLY"),
                &AuthPin::from("user-pin-TEST-ONLY"),
            )
            .expect("the token is provisioned");
        // The key is made once, here: the tests start their sidecars in parallel, and two
        // that each made a missing key would leave two keys under one label.
        module
            .open(TOKEN, &AuthPin::from("user-pin-TEST-ONLY"))
            .and_then(|token| token.signing_key("sig", ti_hsm_proxy::Curve::P256))
            .expect("the signing key is on the token");
        module
    })
}

fn proxy() -> Arc<HsmProxy> {
    let pool = module()
        .pool(
            TOKEN,
            &AuthPin::from("user-pin-TEST-ONLY"),
            NonZeroUsize::new(2).unwrap(),
        )
        .unwrap();
    let keys = [KeySpec {
        key_id: "sig".to_owned(),
        kind: KeyKind::EcdsaP256,
    }];
    Arc::new(
        HsmProxy::start(
            pool,
            &keys,
            MissingKeys::Refuse,
            Duration::from_secs(5),
            Iv::Random,
            String::new(),
        )
        .unwrap(),
    )
}

/// Starts the sidecar on a free port of 127.0.0.1 and returns the port once it accepts
/// connections. A port is free when it is picked, but another process may take it before the
/// sidecar binds it; then the sidecar is started again on another one.
fn start(
    runtime: &tokio::runtime::Runtime,
    listener: impl Fn(SocketAddr) -> Listener,
) -> SocketAddr {
    for _ in 0..5 {
        let address = free_address();
        let server = runtime.spawn(grpc::serve(
            proxy(),
            listener(address),
            Duration::from_secs(5),
            std::future::pending(),
        ));
        for _ in 0..100 {
            if std::net::TcpStream::connect(address).is_ok() {
                return address;
            }
            if server.is_finished() {
                break;
            }
            std::thread::sleep(Duration::from_millis(50));
        }
        server.abort();
    }
    panic!("the sidecar did not come up on any of five ports");
}

fn free_address() -> SocketAddr {
    std::net::TcpListener::bind("127.0.0.1:0")
        .unwrap()
        .local_addr()
        .unwrap()
}

fn probe_socket(name: &str) -> PathBuf {
    std::env::temp_dir().join(format!("hsm-proxy-{name}-{}.sock", std::process::id()))
}

fn sign() -> SignRequest {
    SignRequest {
        key_id: "sig".to_owned(),
        data: vec![7; 32],
        algorithm: 0,
    }
}

/// A channel to `address`, tried until the listener answers or ten seconds have passed.
async fn channel(endpoint: Endpoint) -> Result<Channel, tonic::transport::Error> {
    let mut last = None;
    for _ in 0..100 {
        match endpoint.connect().await {
            Ok(channel) => return Ok(channel),
            Err(e) => last = Some(e),
        }
        tokio::time::sleep(Duration::from_millis(100)).await;
    }
    Err(last.unwrap())
}

fn tls_endpoint(address: SocketAddr, ca: &Ca, client: Option<&Issued>) -> Endpoint {
    let mut tls = ClientTlsConfig::new()
        .ca_certificate(Certificate::from_pem(&ca.cert))
        .domain_name("localhost");
    if let Some(client) = client {
        tls = tls.identity(Identity::from_pem(&client.cert, &client.key));
    }
    Endpoint::from_shared(format!("https://{address}"))
        .unwrap()
        .tls_config(tls)
        .unwrap()
        .connect_timeout(Duration::from_secs(5))
}

/// servers.md rule 29: over its own mTLS the sidecar answers the interface only to a client
/// whose certificate names an identity of the allowlist; one of another identity, one
/// without a certificate and one with an expired certificate are refused. grpc.health.v1
/// answers without a client certificate, as a probe has none (rule 31), and the health
/// socket beside the listener answers `hsm-proxy health`.
#[test]
#[ignore = "needs TI_HSM_PKCS11_MODULE_PATH: just hsm-proxy-softhsm2"]
fn servers_rule_29_mtls_admits_the_allowlist_and_nobody_else() {
    let ca = Ca::new("hsm-proxy CA");
    let server = ca.issue(
        "hsm-proxy",
        vec![dns("localhost"), loopback()],
        valid_for(1),
    );
    let pep = ca.issue("pep", vec![uri("spiffe://zeta/pep")], valid_for(1));
    let stranger = ca.issue(
        "stranger",
        vec![uri("spiffe://zeta/stranger")],
        valid_for(1),
    );
    let old = ca.issue("pep", vec![uri("spiffe://zeta/pep")], expired());
    let probe = probe_socket("mtls");
    let runtime = tokio::runtime::Runtime::new().unwrap();
    let address = start(&runtime, |address| Listener::Tls {
        address,
        tls: TlsListener::new(
            server.cert.as_bytes(),
            server.key.as_bytes(),
            Some(Clients {
                ca: ca.cert.as_bytes(),
                allow: vec!["spiffe://zeta/pep".to_owned()],
            }),
            SystemTime::now(),
        )
        .unwrap(),
        probe: probe.clone(),
    });
    runtime.block_on(async {
        let admitted = channel(tls_endpoint(address, &ca, Some(&pep)))
            .await
            .unwrap();
        let signature = HsmProxyServiceClient::new(admitted)
            .sign(sign())
            .await
            .unwrap();
        assert_eq!(signature.into_inner().signature.len(), 64);

        let other = channel(tls_endpoint(address, &ca, Some(&stranger)))
            .await
            .unwrap();
        let refused = HsmProxyServiceClient::new(other)
            .sign(sign())
            .await
            .unwrap_err();
        assert_eq!(refused.code(), Code::Unauthenticated, "{refused}");

        let anonymous = channel(tls_endpoint(address, &ca, None)).await.unwrap();
        let refused = HsmProxyServiceClient::new(anonymous.clone())
            .sign(sign())
            .await
            .unwrap_err();
        assert_eq!(refused.code(), Code::Unauthenticated, "{refused}");
        let health = tonic_health::pb::health_client::HealthClient::new(anonymous)
            .check(tonic_health::pb::HealthCheckRequest {
                service: String::new(),
            })
            .await
            .unwrap();
        assert_eq!(health.into_inner().status, 1, "SERVING");

        let expired = tls_endpoint(address, &ca, Some(&old)).connect().await;
        let refused = match expired {
            Err(_) => true,
            Ok(channel) => HsmProxyServiceClient::new(channel)
                .sign(sign())
                .await
                .is_err(),
        };
        assert!(refused, "an expired client certificate was taken");

        assert!(grpc::probe(&probe).await.unwrap());
    });
}

/// servers.md rule 29: plaintext inside the cluster, for a declared mesh: the interface
/// answers over h2c without TLS, the caller is the mesh's to check, and the health socket
/// answers `hsm-proxy health`.
#[test]
#[ignore = "needs TI_HSM_PKCS11_MODULE_PATH: just hsm-proxy-softhsm2"]
fn servers_rule_29_plaintext_in_the_cluster_for_a_declared_mesh() {
    let probe = probe_socket("mesh");
    let runtime = tokio::runtime::Runtime::new().unwrap();
    let address = start(&runtime, |address| Listener::Mesh {
        address,
        probe: probe.clone(),
    });
    runtime.block_on(async {
        let plain = channel(Endpoint::from_shared(format!("http://{address}")).unwrap())
            .await
            .unwrap();
        let signature = HsmProxyServiceClient::new(plain)
            .sign(sign())
            .await
            .unwrap();
        assert_eq!(signature.into_inner().signature.len(), 64);
        assert!(grpc::probe(&probe).await.unwrap());
    });
}
