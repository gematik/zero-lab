#!/usr/bin/env bash
# Generates a fresh PKCS#12 conformance corpus and runs every available
# decoder against it; writes matrix.md. See ../CONFORMANCE.md.
#
#   ./run.sh            all decoders whose toolchain is installed
#   ./run.sh go rust    only these
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
decoders=("$@")
[ ${#decoders[@]} -eq 0 ] && decoders=(go go-legacy rust openssl python java)

(cd "$here/../tool" && go build -o "$work/p12conformance" .)
"$work/p12conformance" generate -manifest "$here/../testdata/manifest.json" -out "$work/corpus"

matrix="$here/matrix.md"
{
  echo "# Interoperability matrix"
  echo
  echo "Generated by \`interop/run.sh\` on $(date -u +%Y-%m-%d) with $(openssl version)."
  echo "Full comparison checks result codes and the MAC algorithm; coarse comparison checks"
  echo "success or failure only, for decoders that report no reason."
} > "$matrix"

details="$work/details.md"
summary=()
verify() { # name profile mode command...
  local name=$1 profile=$2 mode=$3; shift 3
  local flags=(-corpus "$work/corpus" -profile "$profile" -timeout 20s -markdown "$details" -name "$name")
  [ "$mode" = coarse ] && flags+=(-coarse)
  echo "==> $name"
  local result
  result=$("$work/p12conformance" verify "${flags[@]}" -- "$@" | tail -1 || true)
  echo "$result"
  summary+=("| $name | $profile | $mode | ${result% cases pass*} |")
}

for d in "${decoders[@]}"; do
  case $d in
    go)
      (cd "$here/go" && GOWORK=off go build -o "$work/decoder-go" .)
      verify "go/pkcs12 (pkcs12.Decode)" modern full "$work/decoder-go" ;;
    go-legacy)
      (cd "$here/go" && GOWORK=off go build -o "$work/decoder-go" .)
      verify "go/pkcs12 (legacy.Decode)" legacy full "$work/decoder-go" -legacy ;;
    rust)
      command -v cargo >/dev/null || { echo "skip rust: no cargo"; continue; }
      (cd "$here/rust" && cargo build --release -q)
      verify "rust/ti-pkcs12" legacy full "$here/rust/target/release/p12-decoder-rust" ;;
    openssl)
      verify "OpenSSL $(openssl version | awk '{print $2}') CLI" legacy coarse python3 -I "$here/openssl/decoder.py" ;;
    python)
      python3 -c 'import cryptography' 2>/dev/null || { echo "skip python: no cryptography"; continue; }
      verify "pyca/cryptography $(python3 -c 'import cryptography; print(cryptography.__version__)')" legacy coarse \
        python3 -I "$here/python/decoder.py" ;;
    java)
      command -v javac >/dev/null || { echo "skip java: no JDK"; continue; }
      javac -d "$work/java" "$here/java/Decoder.java"
      verify "JDK $(java -version 2>&1 | awk -F'"' 'NR==1{print $2}') KeyStore PKCS12" legacy coarse java -cp "$work/java" Decoder ;;
    *) echo "unknown decoder $d" >&2; exit 2 ;;
  esac
done
{
  echo
  echo "## Summary"
  echo
  echo "| Decoder | Profile | Comparison | Passing cases |"
  echo "|---|---|---|---|"
  printf '%s\n' "${summary[@]}"
  echo
  echo "## Cases"
  cat "$details"
} >> "$matrix"
echo "wrote $matrix"
